/* Opens up the popup box  and where buttons are */

const projectButtons = document.querySelectorAll(".project-open");

const lightbox = document.getElementById("project-lightbox");

const closeButton = document.getElementById("lightbox-close");

const title = document.getElementById("lightbox-title");

const category = document.getElementById("lightbox-category");

const description = document.getElementById("lightbox-description");

const client = document.getElementById("lightbox-client");

const role = document.getElementById("lightbox-role");

const gallery = document.getElementById("lightbox-gallery");


const storyLink = document.getElementById("lightbox-story-link");


/* Controls what happens when user clicks */
projectButtons.forEach(button => {

    button.addEventListener("click", () => {

        console.log("PROJECT BUTTON WAS CLICKED!");
        const projectName = button.dataset.project;

        const project = projects[projectName];

        title.textContent = project.title;
        category.textContent = project.category;
        description.textContent = project.description;
        client.textContent = project.client;
        role.textContent = project.role;

        storyLink.href = project.storyUrl || "#";
        storyLink.style.display = project.storyUrl ? "inline-block" : "none";

        gallery.innerHTML = "";

        project.images.forEach(item => {
         if (item.type === "image") {

        const img = document.createElement("img");

        img.src = item.src;
        img.alt = item.caption || project.title;

        gallery.appendChild(img);


        }
        if (item.type === "text") {

        const textBlock = document.createElement("div");

        textBlock.classList.add("lightbox-story-text");

// Apply the layout specified in the project data
    if (item.style) {
        textBlock.classList.add(`text-${item.style}`);
    }
        textBlock.textContent = item.text;

        gallery.appendChild(textBlock);

        }

        });

        lightbox.classList.add("active");

  });

});



/* Allows user to close and Esc */ 
closeButton.addEventListener("click", () => {

    lightbox.classList.remove("active");

});

document.addEventListener("keydown", event => {

    if (event.key === "Escape") {

        lightbox.classList.remove("active");

    }

});